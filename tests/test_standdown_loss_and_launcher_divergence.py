def test_removed_launcher_is_not_reported(cli):
    """A launcher the operator deleted is not a divergence -- nagging about it forever would
    train the operator to ignore the notice that matters."""
    launcher = _generated_launcher(cli.USER_BIN_DIR / "yolo")
    cli.record_installed_launcher(launcher)
    launcher.unlink()
    assert cli.diverged_installed_launchers() == []


def test_launcher_replaced_by_a_binary_is_reported_without_hashing_it(cli):
    """A recorded path that has become a binary (or anything over the scan cap) is a replacement
    and must be reported -- but the size cap is what keeps every launch from reading it end to
    end, so the report cannot be allowed to depend on hashing it first."""
    launcher = _generated_launcher(cli.USER_BIN_DIR / "yolo")
    cli.record_installed_launcher(launcher)

    launcher.write_bytes(b"\x7fELF\x00\x00" + b"\x00" * 64)

    assert cli._launcher_digest(launcher) is not None  # small: still hashable
    assert cli._launcher_looks_generated(launcher) is False
    assert cli.diverged_installed_launchers() == [
        (launcher, cli.LAUNCHER_DIVERGENCE_HAND_REPLACED)
    ]

    # Over the scan cap: never hashed, still reported.
    launcher.write_bytes(b"#" * (cli.LAUNCHER_SCAN_MAX_BYTES + 1))
    assert cli._launcher_digest(launcher) is None
    assert cli.diverged_installed_launchers() == [
        (launcher, cli.LAUNCHER_DIVERGENCE_HAND_REPLACED)
    ]


