"""RCA 2026-07-22 controls 2 and 4: a lost maintainer-mode standdown, and generated launchers
that no longer match the generator.

Both controls exist because of one incident. An operator whose exec-root deliberately tracks a
non-release branch had maintainer mode armed -- the supported machine-wide update-gate standdown.
A later session hand-rewrote the config env file for an unrelated reason, the mode key did not
survive that rewrite, and NOTHING reported the loss. The next launch through a different entry
point hit the non-release-branch refusal again, two days after the failure was declared closed.

Control 2 (this file's first half): arming leaves a marker in the state dir. `maintainer-mode off`
removes it -- that is an authorized disarm. A marker with no key anywhere is an UNAUTHORIZED
disarm: something edited the config env behind the mode's back, and every launch surface says so
until the operator either re-arms or accepts the disarm through the verb.

Control 4 (second half): a launcher this machine recorded as generated must still be the
generator's output. Two independent detections, because the record predates digests: content that
no longer carries the generated marker is a hand-replacement (detectable with no digest at all --
this is the July-20 class), and a recorded digest that no longer matches is an in-place edit.
"""
import json
from pathlib import Path

import pytest

from test_maintainer_mode import (
    _cli_module_for_home,
    _config_env_path,
    _maintainer_home,
    _sync_env,
    _verb,
)
from test_sync_methodology_cli import _make_methodology_fixture, _run_cli


@pytest.fixture()
def cli(monkeypatch, tmp_path):
    """A fresh CLI module per test with a hermetic HOME (see test_maintainer_mode)."""
    return _cli_module_for_home(monkeypatch, tmp_path / "home")


def _arm_key(cli) -> Path:
    config = cli.USER_CONFIG_ENV
    config.parent.mkdir(parents=True, exist_ok=True)
    config.write_text("export TAUTLINE_METHODOLOGY_MAINTAINER_MODE=1\n", encoding="utf-8")
    return config


def _generated_launcher(path: Path, body: str = "exec claude\n") -> Path:
    """A file shaped like the generator's output: the generated marker plus a body."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"#!/bin/sh\n# {_GENERATED}\n{body}", encoding="utf-8")
    path.chmod(0o755)
    return path


_GENERATED = "Generated by tautline install-claude-launcher."


# --- Control 2: a lost standdown -----------------------------------------------------------


def test_never_armed_machine_never_reports_a_loss(cli):
    """No marker, no key: a stock machine must stay silent. The notice keys on the MARKER, not
    on the absence of the key, or every machine on earth would nag."""
    assert cli.read_maintainer_mode_arm_marker() is None
    assert cli.maintainer_mode_standdown_lost() is False
    assert cli.maintainer_mode_standdown_loss_lines() == []


def test_arm_marker_roundtrips_and_clears(cli):
    config = _arm_key(cli)
    written = cli.write_maintainer_mode_arm_marker(config)
    assert written == cli.maintainer_mode_arm_marker_path()

    marker = cli.read_maintainer_mode_arm_marker()
    assert marker is not None
    assert marker["schema"] == cli.MAINTAINER_MODE_ARM_MARKER_SCHEMA
    assert marker["configEnv"] == str(config)
    assert marker["armedAt"]

    assert cli.clear_maintainer_mode_arm_marker() is True
    assert cli.read_maintainer_mode_arm_marker() is None
    # Idempotent: clearing an already-clear machine is not an error.
    assert cli.clear_maintainer_mode_arm_marker() is False


def test_backfill_arms_the_witness_on_an_already_armed_machine(cli):
    """Without the backfill this control protects nobody who already needs it: a machine armed
    before the control shipped carries no marker, so a later silent disarm reports nothing --
    on exactly the machines the RCA is about."""
    config = _arm_key(cli)
    assert cli.read_maintainer_mode_arm_marker() is None

    cli.ensure_maintainer_mode_arm_marker()
    marker = cli.read_maintainer_mode_arm_marker()
    assert marker is not None
    assert marker["source"] == "observed", "a backfill must not claim to be a real arming"
    assert marker["configEnv"] == str(config)

    # Idempotent, and it never fabricates a marker on an unarmed machine.
    cli.ensure_maintainer_mode_arm_marker()
    assert cli.read_maintainer_mode_arm_marker()["armedAt"] == marker["armedAt"]
    config.unlink()
    cli.clear_maintainer_mode_arm_marker()
    cli.ensure_maintainer_mode_arm_marker()
    assert cli.read_maintainer_mode_arm_marker() is None


def test_backfill_refuses_when_the_mode_is_configured_but_not_armed(cli, monkeypatch, tmp_path):
    """Codex R2 P2. `configured but not armed` means the key is set with no checkout to manage:
    every gate runs stock and no standdown exists. A marker there would be a witness to nothing,
    and a later config cleanup would report the loss of a standdown that never stood down --
    a permanent false alarm on a machine that was never protected."""
    _arm_key(cli)
    # No checkout to manage -> configured, but not armed.
    monkeypatch.setattr(cli, "canonical_methodology_repo", lambda: tmp_path / "no-checkout")
    assert cli.maintainer_mode_configured() is True
    assert cli.maintainer_mode_armed() is False

    cli.ensure_maintainer_mode_arm_marker()
    assert cli.read_maintainer_mode_arm_marker() is None, (
        "an inert configured-but-not-armed machine must not get a witness"
    )


def test_backfilled_marker_still_detects_the_loss_and_says_it_was_observed(cli):
    config = _arm_key(cli)
    cli.ensure_maintainer_mode_arm_marker()
    config.unlink()
    assert cli.maintainer_mode_standdown_lost() is True
    greppable = [
        line
        for line in cli.maintainer_mode_standdown_loss_lines()
        if line.startswith("maintainer_mode_standdown_lost: ")
    ]
    assert "observed armed" in greppable[0], greppable


def test_marker_plus_live_key_is_not_a_loss(cli):
    config = _arm_key(cli)
    cli.write_maintainer_mode_arm_marker(config)
    assert cli.maintainer_mode_configured() is True
    assert cli.maintainer_mode_standdown_lost() is False
    assert cli.maintainer_mode_standdown_loss_lines() == []


def test_key_vanishing_from_every_surface_is_a_loss(cli):
    """THE incident, reduced: armed, then the config env is rewritten without the key."""
    config = _arm_key(cli)
    cli.write_maintainer_mode_arm_marker(config)

    # A hand-rewrite of the config env that drops the key -- exactly what happened on 2026-07-20.
    config.write_text("export TAUTLINE_METHODOLOGY_REPO=/somewhere\n", encoding="utf-8")

    assert cli.maintainer_mode_configured() is False
    assert cli.maintainer_mode_standdown_lost() is True


def test_loss_notice_names_both_remedies_and_stays_greppable(cli):
    config = _arm_key(cli)
    cli.write_maintainer_mode_arm_marker(config)
    config.unlink()

    lines = cli.maintainer_mode_standdown_loss_lines()
    assert lines, "a lost standdown must produce a notice"
    body = "\n".join(lines)
    # Re-arm, and the authorized way to accept the disarm and silence the notice.
    assert f"{cli.CLI_NAME} maintainer-mode on" in body
    assert f"{cli.CLI_NAME} maintainer-mode off" in body
    # One unprefixed machine-readable line, like every other `key: value` report line.
    greppable = [line for line in lines if line.startswith("maintainer_mode_standdown_lost: ")]
    assert len(greppable) == 1, lines
    assert str(config) in greppable[0]


def test_config_surface_deleted_entirely_is_still_a_loss(cli):
    """Deleting the file is the same unauthorized disarm as editing the key out of it."""
    config = _arm_key(cli)
    cli.write_maintainer_mode_arm_marker(config)
    config.unlink()
    assert cli.maintainer_mode_standdown_lost() is True


def test_unreadable_marker_never_reports_a_loss(cli):
    """Corrupt state is not evidence of a disarm. Fail silent, never nag on garbage."""
    path = cli.maintainer_mode_arm_marker_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("{not json", encoding="utf-8")
    assert cli.read_maintainer_mode_arm_marker() is None
    assert cli.maintainer_mode_standdown_lost() is False


def test_status_line_reports_the_loss(cli):
    config = _arm_key(cli)
    cli.write_maintainer_mode_arm_marker(config)
    config.unlink()
    assert cli.maintainer_mode_status_line() == "maintainer_mode: off"
    assert cli.maintainer_mode_standdown_lost() is True


# --- Control 2: verb wiring (subprocess, real CLI) -------------------------------------------


def _marker_path(home: Path) -> Path:
    return home / ".local" / "state" / "minervit" / "maintainer-mode-armed.json"


def test_verb_on_writes_the_marker_and_off_clears_it(tmp_path):
    _source, clone, _lane = _make_methodology_fixture(tmp_path)
    home = _maintainer_home(tmp_path)

    on = _verb(clone, home, "on")
    assert on.returncode == 0, on.stdout + on.stderr
    marker = _marker_path(home)
    assert marker.is_file(), "arming must record that this machine was armed"
    assert json.loads(marker.read_text(encoding="utf-8"))["configEnv"] == str(
        _config_env_path(home)
    )

    off = _verb(clone, home, "off")
    assert off.returncode == 0, off.stdout + off.stderr
    assert not marker.exists(), "an authorized disarm must leave no loss notice behind"


def test_status_and_sync_report_an_unauthorized_disarm(tmp_path):
    """Arm, then strip the key the way a hand-rewrite would. Both the verb and the launch path
    must say so -- the launch path is the one that would have caught the incident."""
    _source, clone, _lane = _make_methodology_fixture(tmp_path)
    home = _maintainer_home(tmp_path)

    assert _verb(clone, home, "on").returncode == 0
    config = _config_env_path(home)
    config.write_text("export TAUTLINE_METHODOLOGY_REPO=/somewhere\n", encoding="utf-8")

    status = _verb(clone, home, "status")
    assert status.returncode == 0, status.stdout + status.stderr
    assert "maintainer_mode_standdown_lost:" in status.stdout + status.stderr

    sync = _run_cli(
        clone / "bin" / "tautline",
        "sync-methodology",
        "--no-remote",
        cwd=clone,
        env=_sync_env(home),
    )
    assert "maintainer_mode_standdown_lost:" in sync.stdout + sync.stderr, (
        sync.stdout + sync.stderr
    )


