    launcher.write_text("#!/bin/sh\nhand written\n", encoding="utf-8")

    body = "\n".join(cli.launcher_divergence_lines(cli.diverged_installed_launchers()))
    assert f"--bin-dir {elsewhere}" in body
    assert "--operator-channel experimental" in body
    assert "originally installed with" not in body, "metadata was recorded; do not hedge"


